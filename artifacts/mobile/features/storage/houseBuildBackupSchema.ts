import { z } from 'zod';

const id = z.string().min(1).max(200);
const text = z.string().max(100_000);
const number = z.number().finite();
const integer = number.int();
const jsonObject = text.refine(raw => {
  try {
    const value = JSON.parse(raw);
    return value !== null && typeof value === 'object' && !Array.isArray(value);
  } catch {
    return false;
  }
});
const jsonStringList = text.refine(raw => {
  try {
    return z.array(text).max(1000).safeParse(JSON.parse(raw)).success;
  } catch {
    return false;
  }
});
const webLink = text.refine(raw => raw === '' || /^https?:\/\//i.test(raw));

